function makeScenicCircuitGrid(
  prefix: string,
  xs: number[],
  zs: number[],
  northSouthNames: string[],
  eastWestNames: string[],
  surface: 'cobblestone' | 'asphalt' | 'campus_paver' | 'boulevard',
  width = 11.5,
): RoadSegmentSpec[] {
  const segs: RoadSegmentSpec[] = [];
  const minX = Math.min(...xs) - 24;
  const maxX = Math.max(...xs) + 24;
  const minZ = Math.min(...zs) - 24;
  const maxZ = Math.max(...zs) + 24;

  xs.forEach((x, idx) => {
    segs.push({
      id: `${prefix}_ns_${idx}`,
      name: northSouthNames[idx] || `Tramo Norte-Sur ${idx + 1}`,
      points: [
        { x, z: minZ },
        { x, z: maxZ },
      ],
      width: idx === Math.floor(xs.length / 2) ? width + 2 : width,
      lanes: 2,
      surface,
      isMainArtery: idx === Math.floor(xs.length / 2),
    });
  });

  zs.forEach((z, idx) => {
    segs.push({
      id: `${prefix}_ew_${idx}`,
      name: eastWestNames[idx] || `Tramo Transversal ${idx + 1}`,
      points: [
        { x: minX, z },
        { x: maxX, z },
      ],
      width: idx === Math.floor(zs.length / 2) ? width + 2 : width,
      lanes: 2,
      surface,
      isMainArtery: idx === Math.floor(zs.length / 2),
    });
  });

  return segs;
}

